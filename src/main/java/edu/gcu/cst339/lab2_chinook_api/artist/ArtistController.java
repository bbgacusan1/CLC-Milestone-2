package edu.gcu.cst339.lab2_chinook_api.artist;

import java.util.List;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

import org.springframework.web.bind.annotation.RequestBody;

/**
 * REST controller that exposes CRUD operations for Chinook artists at
 * {@code /api/artists}.
 *
 * <p>All work is delegated to {@link ArtistService}. A missing artist ID results
 * in HTTP 404 through {@link ArtistNotFoundException}. Request bodies are not
 * annotated with {@code @Valid}, so a name longer than 120 characters is only
 * rejected when the database or JPA validation checks it.</p>
 */
@RestController 
@RequestMapping("/api/artists")
class ArtistController {
    private final ArtistService artistService;

    /**
     * Creates the controller. Spring injects the service through this constructor.
     *
     * @param artistService the service that performs artist operations
     */
    ArtistController(ArtistService artistService) {
        this.artistService = artistService;
    }

    /**
     * Handles {@code GET /api/artists}.
     *
     * @return all artists (HTTP 200)
     */
    @GetMapping
    List<ArtistDto> findAll() {
        return artistService.findAll();
    }

    /**
     * Handles {@code GET /api/artists/{id}}.
     *
     * @param id the artist ID from the URL
     * @return the matching artist (HTTP 200)
     * @throws ArtistNotFoundException if no artist has the given ID (HTTP 404)
     */
    @GetMapping("/{id}")
    ArtistDto findById(@PathVariable Integer id) {
        return artistService.findById(id);
    }

    /**
     * Handles {@code POST /api/artists}. The artist ID is generated by the database.
     *
     * @param dto the new artist's name, read from the JSON body
     * @return the created artist including its new ID (HTTP 201 Created)
     */
    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    ArtistDto create(@RequestBody ArtistDto dto) {
        return artistService.create(dto);
    }

    /**
     * Handles {@code PUT /api/artists/{id}} by replacing the artist's name.
     *
     * @param id  the ID of the artist to update, from the URL
     * @param dto the new name, read from the JSON body; any {@code artistId} in the body is ignored
     * @return the updated artist (HTTP 200)
     * @throws ArtistNotFoundException if no artist has the given ID (HTTP 404)
     */
    @PutMapping("/{id}")
    ResponseEntity<ArtistDto> update(@PathVariable Integer id, @RequestBody ArtistDto dto) {
        ArtistDto updated = artistService.update(id, dto);
        return ResponseEntity.ok(updated);
    }

    /**
     * Handles {@code DELETE /api/artists/{id}}.
     *
     * <p>An artist that still has albums cannot be deleted because of the
     * {@code album.artist_id} foreign key. This controller has no conflict handler,
     * so that case is not translated into HTTP 409.</p>
     *
     * @param id the ID of the artist to delete, from the URL
     * @return an empty response (HTTP 204 No Content)
     * @throws ArtistNotFoundException if no artist has the given ID (HTTP 404)
     */
    @DeleteMapping("/{id}")
    ResponseEntity<Void> delete(@PathVariable Integer id) {
        artistService.delete(id);
        return ResponseEntity.noContent().build();
    }
}
