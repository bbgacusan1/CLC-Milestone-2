package edu.gcu.cst339.lab2_chinook_api.track;

import java.net.URI;
import java.util.List;

import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import jakarta.validation.Valid;

/**
 * REST controller that exposes CRUD operations for Chinook tracks at
 * {@code /api/tracks}.
 *
 * <p>All work is delegated to {@link TrackService}. Create and update request
 * bodies are validated with {@code @Valid}. Missing IDs are reported by
 * returning HTTP 404 directly, based on an empty result from the service.</p>
 */
@RestController
@RequestMapping("/api/tracks")
class TrackController {

    private final TrackService trackService;

    /**
     * Creates the controller. Spring injects the service through this constructor.
     *
     * @param trackService the service that performs track operations
     */
    TrackController(TrackService trackService) {
        this.trackService = trackService;
    }

    /**
     * Handles {@code GET /api/tracks}.
     *
     * @return all tracks (HTTP 200)
     */
    @GetMapping
    List<TrackDto> findAll() {
        return trackService.getAllTracks();
    }

    /**
     * Handles {@code GET /api/tracks/{id}}.
     *
     * @param id the track ID from the URL
     * @return the track (HTTP 200), or HTTP 404 if no track has that ID
     */
    @GetMapping("/{id}")
    ResponseEntity<TrackDto> findById(@PathVariable Integer id) {
        return trackService.getTrackById(id)
                .map(ResponseEntity::ok)                      // found: 200 + the DTO
                .orElse(ResponseEntity.notFound().build());   // empty: 404
    }

    /**
     * Handles {@code POST /api/tracks}. The body is validated before the track is
     * saved, and the track ID is generated by the database.
     *
     * @param dto the new track's details, read from the JSON body
     * @return the created track (HTTP 201 Created) with a {@code Location} header
     *         pointing to {@code /api/tracks/{id}}
     */
    @PostMapping
    ResponseEntity<TrackDto> create(@Valid @RequestBody TrackDto dto) {
        TrackDto created = trackService.createTrack(dto);
        URI location = URI.create("/api/tracks/" + created.trackId());
        return ResponseEntity.created(location).body(created);
    }
 
    /**
     * Handles {@code PUT /api/tracks/{id}} by replacing every editable field of
     * the track with the validated values in the body.
     *
     * @param id  the ID of the track to update, from the URL
     * @param dto the new values, read from the JSON body; any {@code trackId} in the body is ignored
     * @return the updated track (HTTP 200), or HTTP 404 if no track has that ID
     */
    @PutMapping("/{id}")
    ResponseEntity<TrackDto> update(@PathVariable Integer id, @Valid @RequestBody TrackDto dto) {
        return trackService.updateTrack(id, dto)
                .map(ResponseEntity::ok)                      // updated: 200 + the DTO
                .orElse(ResponseEntity.notFound().build());   // no such track: 404
    }

    /**
     * Handles {@code DELETE /api/tracks/{id}}.
     *
     * <p>A track that appears on invoice lines or playlists cannot be deleted
     * because of the {@code invoice_line.track_id} and
     * {@code playlist_track.track_id} foreign keys.</p>
     *
     * @param id the ID of the track to delete, from the URL
     * @return HTTP 204 No Content if the track was deleted, or HTTP 404 if no
     *         track has that ID
     */
    @DeleteMapping("/{id}")
    ResponseEntity<Void> delete(@PathVariable Integer id) {
        if (trackService.deleteTrack(id)) {
            return ResponseEntity.noContent().build();        // deleted: 204, empty body
        }
        return ResponseEntity.notFound().build();             // nothing to delete: 404
    }
}