package edu.gcu.cst339.lab2_chinook_api.customer;

import java.net.URI;
import java.util.List;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

import org.springframework.web.bind.annotation.RequestBody;
import jakarta.validation.Valid;

/**
 * REST controller that exposes CRUD operations for Chinook customers at
 * {@code /api/customers}.
 *
 * <p>All work is delegated to {@link CustomerService}. A missing customer ID
 * results in HTTP 404 through {@link CustomerNotFoundException}. Create requests
 * are validated with {@code @Valid}; update requests are not, so invalid values
 * on update are only caught by the database.</p>
 */
@RestController
@RequestMapping("/api/customers")
class CustomerController {
    private final CustomerService customerService;

    /**
     * Creates the controller. Spring injects the service through this constructor.
     *
     * @param customerService the service that performs customer operations
     */
    CustomerController(CustomerService customerService) {
        this.customerService = customerService;
    }

    /**
     * Handles {@code GET /api/customers}.
     *
     * @return all customers (HTTP 200)
     */
    @GetMapping
    List<CustomerDto> findAll() {
        return customerService.findAll();
    }

    /**
     * Handles {@code GET /api/customers/{id}}.
     *
     * @param id the customer ID from the URL
     * @return the matching customer (HTTP 200)
     * @throws CustomerNotFoundException if no customer has the given ID (HTTP 404)
     */
    @GetMapping("/{id}")
    CustomerDto findById(@PathVariable Integer id) {
        return customerService.findById(id);
    }

    /**
     * Handles {@code POST /api/customers}. The body is validated before the
     * customer is saved, and the customer ID is generated by the database.
     *
     * @param dto the new customer's details, read from the JSON body
     * @return the created customer (HTTP 201 Created) with a {@code Location}
     *         header pointing to {@code /api/customers/{id}}
     */
    @PostMapping
    ResponseEntity<CustomerDto> create(@Valid @RequestBody CustomerDto dto) {
        CustomerDto created = customerService.create(dto);
        URI location = URI.create("/api/customers/" + created.customerId());
        return ResponseEntity.created(location).body(created);
    }

    /**
     * Handles {@code PUT /api/customers/{id}} by replacing every editable field
     * of the customer with the values in the body.
     *
     * @param id  the ID of the customer to update, from the URL
     * @param dto the new values, read from the JSON body; any {@code customerId} in the body is ignored
     * @return the updated customer (HTTP 200)
     * @throws CustomerNotFoundException if no customer has the given ID (HTTP 404)
     */
    @PutMapping("/{id}")
    ResponseEntity<CustomerDto> update(@PathVariable Integer id, @RequestBody CustomerDto dto) {
        CustomerDto updated = customerService.update(id, dto);
        return ResponseEntity.ok(updated);
    }

    /**
     * Handles {@code DELETE /api/customers/{id}}.
     *
     * <p>A customer who still has invoices cannot be deleted because of the
     * {@code invoice.customer_id} foreign key.</p>
     *
     * @param id the ID of the customer to delete, from the URL
     * @return an empty response (HTTP 204 No Content)
     * @throws CustomerNotFoundException if no customer has the given ID (HTTP 404)
     */
    @DeleteMapping("/{id}")
    ResponseEntity<Void> delete(@PathVariable Integer id) {
        customerService.delete(id);
        return ResponseEntity.noContent().build();
    }
}
