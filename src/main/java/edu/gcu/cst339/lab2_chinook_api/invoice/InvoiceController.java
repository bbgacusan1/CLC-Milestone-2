package edu.gcu.cst339.lab2_chinook_api.invoice;

import java.net.URI;
import java.util.List;

import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;

/**
 * REST controller that exposes CRUD operations for Chinook invoices at
 * {@code /api/invoices}.
 *
 * <p>All work is delegated to {@link InvoiceService}. Create and update request
 * bodies are validated with {@code @Valid}; a missing invoice ID results in
 * HTTP 404 through {@link InvoiceNotFoundException}; and foreign-key violations
 * are turned into HTTP 409 Conflict by
 * {@link #handleDataIntegrityViolationException(DataIntegrityViolationException)}.</p>
 */
@Tag(name = "Invoices", description = "The Invoice API")
@RestController
@RequestMapping("/api/invoices")
class InvoiceController {
    
    private final InvoiceService invoiceService;
    
    /**
     * Creates the controller. Spring injects the service through this constructor.
     *
     * @param invoiceService the service that performs invoice operations
     */
    InvoiceController(InvoiceService invoiceService) {
        this.invoiceService = invoiceService;
    }

    /**
     * Handles {@code GET /api/invoices}.
     *
     * @return all invoices (HTTP 200)
     */
    @Operation(summary = "Get all invoices", description = "Returns a list of all invoices")
    @ApiResponse(responseCode = "200", description = "Successfully retrieved list of invoices")
    @GetMapping
    List<InvoiceDto> getAll() {
        return invoiceService.findAll();
    }

    /**
     * Handles {@code GET /api/invoices/{id}}.
     *
     * @param id the invoice ID from the URL
     * @return the matching invoice (HTTP 200)
     * @throws InvoiceNotFoundException if no invoice has the given ID (HTTP 404)
     */
    @Operation(summary = "Get invoice by ID", description = "Returns a single invoice by its ID")
    @ApiResponse(responseCode = "200", description = "Successfully retrieved invoice")
    @ApiResponse(responseCode = "404", description = "Invoice not found")
    @GetMapping("/{id}")
    ResponseEntity<InvoiceDto> getById(@PathVariable Integer id) {
        InvoiceDto invoiceDto = invoiceService.findById(id);
        return ResponseEntity.ok(invoiceDto);
    }

    /**
     * Handles {@code POST /api/invoices}. The body is validated before the invoice
     * is saved, and the invoice ID is generated by the database.
     *
     * @param invoiceDto the new invoice's details, read from the JSON body
     * @return the created invoice (HTTP 201 Created) with a {@code Location} header
     *         pointing to {@code /api/invoices/{id}}; HTTP 400 if validation fails;
     *         HTTP 409 if the {@code customerId} does not exist
     */
    @Operation(summary = "Create a new invoice", description = "Creates a new invoice and returns the created invoice")
    @ApiResponse(responseCode = "201", description = "Invoice created successfully")
    @ApiResponse(responseCode = "400", description = "Invalid input data")
    @ApiResponse(responseCode = "409", description = "Conflict: customerId does not exist")
    @PostMapping
    ResponseEntity<InvoiceDto> create(@Valid @RequestBody InvoiceDto invoiceDto) {
        InvoiceDto createdInvoice = invoiceService.create(invoiceDto);
        return ResponseEntity.created(URI.create("/api/invoices/" + createdInvoice.invoiceId())).body(createdInvoice);
    }

    /**
     * Handles {@code PUT /api/invoices/{id}} by replacing every editable field of
     * the invoice with the validated values in the body.
     *
     * @param id         the ID of the invoice to update, from the URL
     * @param invoiceDto the new values, read from the JSON body; any {@code invoiceId} in the body is ignored
     * @return the updated invoice (HTTP 200); HTTP 400 if validation fails;
     *         HTTP 409 if the {@code customerId} does not exist
     * @throws InvoiceNotFoundException if no invoice has the given ID (HTTP 404)
     */
    @Operation(summary = "Update an invoice", description = "Updates an existing invoice and returns the updated invoice")
    @ApiResponse(responseCode = "200", description = "Invoice updated successfully")
    @ApiResponse(responseCode = "400", description = "Invalid input data")
    @ApiResponse(responseCode = "404", description = "Invoice not found")
    @ApiResponse(responseCode = "409", description = "Conflict: customerId does not exist")
    @PutMapping("/{id}")
    ResponseEntity<InvoiceDto> update(@PathVariable Integer id, @Valid @RequestBody InvoiceDto invoiceDto) {
        InvoiceDto updatedInvoice = invoiceService.update(id, invoiceDto);
        return ResponseEntity.ok(updatedInvoice);
    }

    /**
     * Handles {@code DELETE /api/invoices/{id}}.
     *
     * @param id the ID of the invoice to delete, from the URL
     * @return an empty response (HTTP 204 No Content); HTTP 409 if the invoice
     *         still has invoice lines
     * @throws InvoiceNotFoundException if no invoice has the given ID (HTTP 404)
     */
    @Operation(summary = "Delete an invoice", description = "Deletes an existing invoice by its ID")
    @ApiResponse(responseCode = "204", description = "Invoice deleted successfully")
    @ApiResponse(responseCode = "404", description = "Invoice not found")
    @ApiResponse(responseCode = "409", description = "Conflict: Invoice still has invoice lines and cannot be deleted")
    @DeleteMapping("/{id}")
    ResponseEntity<Void> delete(@PathVariable Integer id) {
        invoiceService.delete(id);
        return ResponseEntity.noContent().build();
    }

    /**
     * Converts database constraint violations into HTTP 409 Conflict responses.
     *
     * <p>Triggered when a create or update references a {@code customerId} that does
     * not exist, or when a delete is blocked because invoice lines still reference
     * the invoice.</p>
     *
     * @param ex the constraint violation raised by the database
     * @return a 409 Conflict response with a short explanation in the body
     */
    @ExceptionHandler(DataIntegrityViolationException.class)
    ResponseEntity<String> handleDataIntegrityViolationException(DataIntegrityViolationException ex) {
        return ResponseEntity.status(HttpStatus.CONFLICT).body("Request conflicts with existing data: the customerId may not exist, or the invoice still has invoice lines.");
    }
}
