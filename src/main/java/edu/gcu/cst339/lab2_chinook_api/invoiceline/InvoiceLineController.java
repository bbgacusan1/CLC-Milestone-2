package edu.gcu.cst339.lab2_chinook_api.invoiceline;

import java.net.URI;
import java.util.List;

import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;

/**
 * REST controller that exposes CRUD operations for Chinook invoice lines at
 * {@code /api/invoice-lines}.
 *
 * <p>All work is delegated to {@link InvoiceLineService}. Create and update
 * request bodies are validated with {@code @Valid}; a missing invoice line ID
 * results in HTTP 404 through {@link InvoiceLineNotFoundException}; and an
 * unknown {@code invoiceId} or {@code trackId} is turned into HTTP 409 Conflict by
 * {@link #handleDataIntegrityViolationException(DataIntegrityViolationException)}.</p>
 */
@Tag(name = "Invoice Lines", description = "The Invoice Line API")
@RestController
@RequestMapping("/api/invoice-lines")
class InvoiceLineController {
    
    private final InvoiceLineService invoiceLineService;
    
    /**
     * Creates the controller. Spring injects the service through this constructor.
     *
     * @param invoiceLineService the service that performs invoice line operations
     */
    InvoiceLineController(InvoiceLineService invoiceLineService) {
        this.invoiceLineService = invoiceLineService;
    }

    /**
     * Handles {@code GET /api/invoice-lines}.
     *
     * @return all invoice lines (HTTP 200)
     */
    @Operation(summary = "Get all invoice lines", description = "Returns a list of all invoice lines")
    @ApiResponse(responseCode = "200", description = "Successfully retrieved list of invoice lines")
    @GetMapping
    List<InvoiceLineDto> getAll() {
        return invoiceLineService.findAll();
    }

    /**
     * Handles {@code GET /api/invoice-lines/{id}}.
     *
     * @param id the invoice line ID from the URL
     * @return the matching invoice line (HTTP 200)
     * @throws InvoiceLineNotFoundException if no invoice line has the given ID (HTTP 404)
     */
    @Operation(summary = "Get invoice line by ID", description = "Returns a single invoice line by its ID")
    @ApiResponse(responseCode = "200", description = "Successfully retrieved invoice line")
    @ApiResponse(responseCode = "404", description = "Invoice line not found")
    @GetMapping("/{id}")
    ResponseEntity<InvoiceLineDto> getById(@PathVariable Integer id) {
        InvoiceLineDto invoiceLineDto = invoiceLineService.findById(id);
        return ResponseEntity.ok(invoiceLineDto);
    }

    /**
     * Handles {@code POST /api/invoice-lines}. The body is validated before the
     * line is saved, and the invoice line ID is generated by the database.
     *
     * @param invoiceLineDto the new invoice line's details, read from the JSON body
     * @return the created invoice line (HTTP 201 Created) with a {@code Location}
     *         header pointing to {@code /api/invoice-lines/{id}}; HTTP 400 if
     *         validation fails; HTTP 409 if the {@code invoiceId} or {@code trackId}
     *         does not exist
     */
    @Operation(summary = "Create a new invoice line", description = "Creates a new invoice line and returns the created invoice line. The invoiceLineId is generated by the database; omit it from the request.")
    @ApiResponse(responseCode = "201", description = "Invoice line created successfully")
    @ApiResponse(responseCode = "400", description = "Invalid input data")
    @ApiResponse(responseCode = "409", description = "Conflict: invoiceId or trackId does not exist")
    @PostMapping
    ResponseEntity<InvoiceLineDto> create(@Valid @RequestBody InvoiceLineDto invoiceLineDto) {
        InvoiceLineDto createdInvoiceLine = invoiceLineService.create(invoiceLineDto);
        return ResponseEntity.created(URI.create("/api/invoice-lines/" + createdInvoiceLine.invoiceLineId())).body(createdInvoiceLine);
    }

    /**
     * Handles {@code PUT /api/invoice-lines/{id}} by replacing every editable field
     * of the invoice line with the validated values in the body.
     *
     * @param id             the ID of the invoice line to update, from the URL
     * @param invoiceLineDto the new values, read from the JSON body; any
     *                       {@code invoiceLineId} in the body is ignored
     * @return the updated invoice line (HTTP 200); HTTP 400 if validation fails;
     *         HTTP 409 if the {@code invoiceId} or {@code trackId} does not exist
     * @throws InvoiceLineNotFoundException if no invoice line has the given ID (HTTP 404)
     */
    @Operation(summary = "Update an invoice line", description = "Updates an existing invoice line and returns the updated invoice line. The ID comes from the URL; any invoiceLineId in the body is ignored.")
    @ApiResponse(responseCode = "200", description = "Invoice line updated successfully")
    @ApiResponse(responseCode = "400", description = "Invalid input data")
    @ApiResponse(responseCode = "404", description = "Invoice line not found")
    @ApiResponse(responseCode = "409", description = "Conflict: invoiceId or trackId does not exist")
    @PutMapping("/{id}")
    ResponseEntity<InvoiceLineDto> update(@PathVariable Integer id, @Valid @RequestBody InvoiceLineDto invoiceLineDto) {
        InvoiceLineDto updatedInvoiceLine = invoiceLineService.update(id, invoiceLineDto);
        return ResponseEntity.ok(updatedInvoiceLine);
    }

    /**
     * Handles {@code DELETE /api/invoice-lines/{id}}. No other table refers to
     * invoice lines, so a delete is never blocked by a foreign key.
     *
     * @param id the ID of the invoice line to delete, from the URL
     * @return an empty response (HTTP 204 No Content)
     * @throws InvoiceLineNotFoundException if no invoice line has the given ID (HTTP 404)
     */
    @Operation(summary = "Delete an invoice line", description = "Deletes an existing invoice line by its ID")
    @ApiResponse(responseCode = "204", description = "Invoice line deleted successfully")
    @ApiResponse(responseCode = "404", description = "Invoice line not found")
    @DeleteMapping("/{id}")
    ResponseEntity<Void> delete(@PathVariable Integer id) {
        invoiceLineService.delete(id);
        return ResponseEntity.noContent().build();
    }

    /**
     * Converts database constraint violations into HTTP 409 Conflict responses.
     *
     * <p>Triggered when a create or update references an {@code invoiceId} or
     * {@code trackId} that does not exist.</p>
     *
     * @param ex the constraint violation raised by the database
     * @return a 409 Conflict response with a short explanation in the body
     */
    @ExceptionHandler(DataIntegrityViolationException.class)
    ResponseEntity<String> handleDataIntegrityViolationException(DataIntegrityViolationException ex) {
        return ResponseEntity.status(HttpStatus.CONFLICT).body("Request conflicts with existing data: the invoiceId or trackId may not exist.");
    }
}
