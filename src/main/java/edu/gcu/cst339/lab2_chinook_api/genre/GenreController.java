package edu.gcu.cst339.lab2_chinook_api.genre;

import java.net.URI;
import java.util.List;

import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import jakarta.validation.Valid;

/**
 * REST controller that exposes CRUD operations for Chinook genres at
 * {@code /api/genres}.
 *
 * <p>All work is delegated to {@link GenreService}. Create and update request
 * bodies are validated with {@code @Valid}, and a missing genre ID results in
 * HTTP 404 through {@link GenreNotFoundException}.</p>
 */
@RestController
@RequestMapping("/api/genres")
class GenreController {

    private final GenreService genreService;

    /**
     * Creates the controller. Spring injects the service through this constructor.
     *
     * @param genreService the service that performs genre operations
     */
    GenreController(GenreService genreService) {
        this.genreService = genreService;
    }

    /**
     * Handles {@code GET /api/genres}.
     *
     * @return all genres (HTTP 200)
     */
    @GetMapping
    List<GenreDto> findAll() {
        return genreService.findAll();
    }

    /**
     * Handles {@code GET /api/genres/{id}}.
     *
     * @param id the genre ID from the URL
     * @return the matching genre (HTTP 200)
     * @throws GenreNotFoundException if no genre has the given ID (HTTP 404)
     */
    @GetMapping("/{id}")
    GenreDto findById(@PathVariable Integer id) {
        return genreService.findById(id);
    }

    /**
     * Handles {@code POST /api/genres}. The body is validated before the genre is
     * saved, and the genre ID is generated by the database.
     *
     * @param dto the new genre's name, read from the JSON body
     * @return the created genre (HTTP 201 Created) with a {@code Location} header
     *         pointing to {@code /api/genres/{id}}
     */
    @PostMapping
    ResponseEntity<GenreDto> create(@Valid @RequestBody GenreDto dto) {
        GenreDto created = genreService.create(dto);
        URI location = URI.create("/api/genres/" + created.genreId());
        return ResponseEntity.created(location).body(created);
    }

    /**
     * Handles {@code PUT /api/genres/{id}} by replacing the genre's name.
     *
     * @param id  the ID of the genre to update, from the URL
     * @param dto the new name, read from the JSON body; any {@code genreId} in the body is ignored
     * @return the updated genre (HTTP 200)
     * @throws GenreNotFoundException if no genre has the given ID (HTTP 404)
     */
    @PutMapping("/{id}")
    ResponseEntity<GenreDto> update(@PathVariable Integer id, @Valid @RequestBody GenreDto dto) {
        return ResponseEntity.ok(genreService.update(id, dto));
    }

    /**
     * Handles {@code DELETE /api/genres/{id}}.
     *
     * <p>A genre that is still assigned to tracks cannot be deleted because of
     * the {@code track.genre_id} foreign key.</p>
     *
     * @param id the ID of the genre to delete, from the URL
     * @return an empty response (HTTP 204 No Content)
     * @throws GenreNotFoundException if no genre has the given ID (HTTP 404)
     */
    @DeleteMapping("/{id}")
    ResponseEntity<Void> delete(@PathVariable Integer id) {
        genreService.delete(id);
        return ResponseEntity.noContent().build();
    }
}