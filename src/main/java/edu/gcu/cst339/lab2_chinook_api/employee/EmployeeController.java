package edu.gcu.cst339.lab2_chinook_api.employee;

import java.net.URI;
import java.util.List;

import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import jakarta.validation.Valid;

/**
 * REST controller that exposes CRUD operations for Chinook employees at
 * {@code /api/employees}.
 *
 * <p>All work is delegated to {@link EmployeeService}. Create and update
 * request bodies are validated with {@code @Valid}, and a missing employee ID
 * results in HTTP 404 through {@link EmployeeNotFoundException}.</p>
 */
@RestController
@RequestMapping("/api/employees")
class EmployeeController {

    private final EmployeeService employeeService;

    /**
     * Creates the controller. Spring injects the service through this constructor.
     *
     * @param employeeService the service that performs employee operations
     */
    EmployeeController(EmployeeService employeeService) {
        this.employeeService = employeeService;
    }

    /**
     * Handles {@code GET /api/employees}.
     *
     * @return all employees (HTTP 200)
     */
    @GetMapping
    List<EmployeeDto> findAll() {
        return employeeService.findAll();
    }

    /**
     * Handles {@code GET /api/employees/{id}}.
     *
     * @param id the employee ID from the URL
     * @return the matching employee (HTTP 200)
     * @throws EmployeeNotFoundException if no employee has the given ID (HTTP 404)
     */
    @GetMapping("/{id}")
    EmployeeDto findById(@PathVariable Integer id) {
        return employeeService.findById(id);
    }

    /**
     * Handles {@code POST /api/employees}. The body is validated before the
     * employee is saved, and the employee ID is generated by the database.
     *
     * @param dto the new employee's details, read from the JSON body
     * @return the created employee (HTTP 201 Created) with a {@code Location}
     *         header pointing to {@code /api/employees/{id}}
     */
    @PostMapping
    ResponseEntity<EmployeeDto> create(@Valid @RequestBody EmployeeDto dto) {
        EmployeeDto created = employeeService.create(dto);
        URI location = URI.create("/api/employees/" + created.employeeId());
        return ResponseEntity.created(location).body(created);
    }

    /**
     * Handles {@code PUT /api/employees/{id}} by replacing every editable field
     * of the employee with the validated values in the body.
     *
     * @param id  the ID of the employee to update, from the URL
     * @param dto the new values, read from the JSON body; any {@code employeeId} in the body is ignored
     * @return the updated employee (HTTP 200)
     * @throws EmployeeNotFoundException if no employee has the given ID (HTTP 404)
     */
    @PutMapping("/{id}")
    ResponseEntity<EmployeeDto> update(@PathVariable Integer id, @Valid @RequestBody EmployeeDto dto) {
        return ResponseEntity.ok(employeeService.update(id, dto));
    }

    /**
     * Handles {@code DELETE /api/employees/{id}}.
     *
     * <p>An employee who manages other employees or supports customers cannot be
     * deleted because of the {@code employee.reports_to} and
     * {@code customer.support_rep_id} foreign keys.</p>
     *
     * @param id the ID of the employee to delete, from the URL
     * @return an empty response (HTTP 204 No Content)
     * @throws EmployeeNotFoundException if no employee has the given ID (HTTP 404)
     */
    @DeleteMapping("/{id}")
    ResponseEntity<Void> delete(@PathVariable Integer id) {
        employeeService.delete(id);
        return ResponseEntity.noContent().build();
    }
}